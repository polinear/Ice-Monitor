from __future__ import annotations

from pathlib import Path

from expand_kursovaya_docx import (
    build_paragraph,
    insert_before,
    load_document_xml,
    write_docx,
)


def main() -> None:
    repo_root = Path(__file__).resolve().parents[1]
    docx_path = repo_root / "kursovaya" / "Курсовая ГО.docx"
    if not docx_path.exists():
        raise FileNotFoundError(docx_path)

    root, entries, root_open_tag = load_document_xml(docx_path)
    body = root.find("{http://schemas.openxmlformats.org/wordprocessingml/2006/main}body")
    if body is None:
        raise RuntimeError("word/document.xml has no body")

    extra = [
        build_paragraph("5.11. Критерии готовности к внедрению и повторному использованию", "Heading2"),
        build_paragraph(
            "Критерии готовности системы к внедрению в первую очередь связаны с тем, "
            "насколько стабильно воспроизводится полный стек и насколько прозрачен путь "
            "данных от входного видеопотока до аналитического отчёта. Если проект можно "
            "развернуть одной командой, если он устойчив к частичным сбоям и если все "
            "ключевые сервисы имеют понятные статусы, то можно говорить не просто о "
            "работающем прототипе, а о системном решении, пригодном для дальнейшего "
            "использования в учебной или опытной среде."
        ),
        build_paragraph(
            "Повторное использование особенно важно в курсовой работе, потому что проект "
            "должен быть не только показан, но и понятен тому, кто будет его изучать после "
            "защиты. Поэтому в Ice Monitor особое внимание уделено структуре каталогов, "
            "логике запуска и разделению ответственности между сервисами. Такой подход "
            "делает систему удобной для переноса на другую машину, для модификации и для "
            "расширения новыми источниками данных. Иными словами, проект рассчитан не на "
            "разовую демонстрацию, а на дальнейшую жизнь как технологический артефакт."
        ),
        build_paragraph(
            "С точки зрения прикладной инженерии готовность к внедрению определяется не "
            "только корректностью алгоритмов, но и тем, насколько понятны точки отказа и "
            "процедуры восстановления. Если известно, что происходит при недоступности "
            "Kafka, как ведёт себя горячий путь при задержке инференса и каким образом "
            "обновляются витрины данных после ETL, то систему можно сопровождать без "
            "догадок и случайных действий. Это особенно важно для распределённых "
            "архитектур, где ошибка на одном уровне нередко проявляется только через "
            "несколько звеньев."
        ),
        build_paragraph(
            "Для образовательного проекта важна и объяснимость. В Ice Monitor практически "
            "каждое важное решение можно показать и обосновать: почему выбрана именно эта "
            "архитектура сегментации, почему данные разделены на hot и cold path, почему "
            "показатели качества интерпретируются через набор метрик, а не через одно "
            "число, почему используются отдельные витрины для оперативных и исторических "
            "данных. Такая объяснимость делает проект удобным для защиты, потому что "
            "позволяет отвечать на вопросы не ссылкой на случайность, а аргументированной "
            "архитектурной логикой."
        ),
        build_paragraph(
            "В итоге критерии готовности к внедрению сводятся к четырём свойствам: "
            "воспроизводимость, наблюдаемость, модульность и предметная полезность. Ice "
            "Monitor удовлетворяет всем четырём критериям в учебном масштабе и потому "
            "может служить основой для последующих экспериментов, для расширения набора "
            "датчиков и для более глубокого исследования задач компьютерного зрения на "
            "морских изображениях. Именно это делает его сильной курсовой работой с "
            "практическим и методическим потенциалом."
        ),
    ]

    insert_before(body, "ЗАКЛЮЧЕНИЕ", extra)

    write_docx(docx_path, entries, root, root_open_tag)
    print(f"Updated: {docx_path}")


if __name__ == "__main__":
    main()
