from __future__ import annotations

from pathlib import Path

from expand_kursovaya_docx import (
    build_paragraph,
    insert_before,
    load_document_xml,
    write_docx,
)


def main() -> None:
    repo_root = Path(__file__).resolve().parents[1]
    docx_path = repo_root / "kursovaya" / "Курсовая ГО.docx"
    if not docx_path.exists():
        raise FileNotFoundError(docx_path)

    root, entries, root_open_tag = load_document_xml(docx_path)
    body = root.find("{http://schemas.openxmlformats.org/wordprocessingml/2006/main}body")
    if body is None:
        raise RuntimeError("word/document.xml has no body")

    chapter_2_final = [
        build_paragraph("2.9. Интерпретация метрик и практическая значимость результатов", "Heading2"),
        build_paragraph(
            "Интерпретация метрик в задаче сегментации ледовой обстановки требует "
            "аккуратного подхода, поскольку формально высокие показатели не всегда "
            "означают одинаковую прикладную ценность. Например, рост precision может "
            "сопровождаться снижением recall, если модель становится слишком осторожной и "
            "начинает пропускать пограничные случаи. Для бортовой системы наблюдения это "
            "нежелательно: оператор должен получать не только точные, но и достаточно "
            "полные сведения о ледовой обстановке. Поэтому в работе приоритет отдан "
            "комбинации метрик, а не единственному числу."
        ),
        build_paragraph(
            "Наибольшую интерпретационную ценность имеют ошибки на переходных состояниях "
            "между broken_ice и slush_ice. С точки зрения визуального анализа такие ошибки "
            "объяснимы, поскольку границы в реальном изображении нередко размыты, а сама "
            "структура льда меняется непрерывно. Если модель ошибается в пользу более "
            "тяжёлой категории, это в большинстве случаев допустимо с точки зрения "
            "безопасности. Если же она систематически недооценивает опасность, то качество "
            "необходимо пересматривать. Такой способ рассуждения показывает, что метрики "
            "в проекте связаны с предметной областью, а не используются формально."
        ),
        build_paragraph(
            "Для deep learning-подсистемы это особенно важно, поскольку сегментация не "
            "существует в вакууме. Результаты модели становятся входом для вычисления "
            "ice_conc, ice_severity и дальнейшей классификации уровня опасности. Иными "
            "словами, даже небольшое смещение в маске может повлиять на downstream-задачи. "
            "Именно поэтому в проекте уделяется внимание не только среднему качеству, но и "
            "распределению ошибок по классам, по камерам и по типам сцен. Такой анализ "
            "позволяет видеть, где модель действительно надёжна, а где ей требуется "
            "дополнительное дообучение."
        ),
        build_paragraph(
            "Практическая значимость результатов состоит в том, что система не просто "
            "распознаёт объекты, а формирует операционно полезную картину обстановки. "
            "Видеопоток преобразуется в сведения, которые можно хранить, агрегировать, "
            "сравнивать и передавать в аналитические панели. Это превращает модель из "
            "исследовательского прототипа в элемент рабочей информационной системы. Для "
            "курсовой работы такой результат особенно ценен, поскольку демонстрирует "
            "связь между теоретическими метриками и конкретным прикладным эффектом."
        ),
        build_paragraph(
            "По итогам анализа можно сделать вывод, что выбранная стратегия обучения и "
            "оценки качества отвечает предметной задаче. Модель достаточно точна для "
            "прикладного использования в демонстрационном контуре, а её ошибки "
            "сосредоточены в тех областях, где даже человек-эксперт не всегда даёт "
            "однозначную интерпретацию. Это означает, что полученное качество является "
            "не только статистически приемлемым, но и предметно оправданным."
        ),
        build_paragraph(
            "Таким образом, интерпретация метрик в проекте строится по принципу связи "
            "числовых показателей с реальным риском для судна. Это сближает deep learning "
            "с эксплуатационной логикой и делает систему понятной для инженера, оператора "
            "и преподавателя одновременно."
        ),
    ]

    chapter_5_final = [
        build_paragraph("5.9. Подготовка системы к демонстрации и промышленному развитию", "Heading2"),
        build_paragraph(
            "Подготовка системы к демонстрации важна не меньше, чем сама реализация. Для "
            "курсового проекта необходимо, чтобы стек запускался предсказуемо, а сценарий "
            "показа можно было повторить без ручной настройки десятков параметров. В Ice "
            "Monitor это обеспечивается единым набором команд, health checks и понятной "
            "структурой каталогов. Такой подход делает систему пригодной как для защиты "
            "работы, так и для последующего самостоятельного изучения преподавателем или "
            "другим студентом."
        ),
        build_paragraph(
            "На уровне демонстрации особенно важны визуальные артефакты: живой видеопоток, "
            "сегментационная маска, числовые метрики, журнал событий и исторические "
            "графики. Именно в такой форме архитектура становится убедительной, потому что "
            "позволяет за несколько минут показать весь жизненный цикл данных. Пользователь "
            "видит, как кадр появляется в интерфейсе, как модель строит маску, как результат "
            "попадает в таблицу и как аналитический слой превращает отдельные наблюдения в "
            "временной тренд. Для учебной системы это очень сильный эффект."
        ),
        build_paragraph(
            "Если рассматривать развитие проекта дальше, то наиболее логичными шагами "
            "будут расширение набора камер, переход к потокам RTSP, использование "
            "аппаратного ускорения и увеличение числа узлов в кластере данных. В этом случае "
            "Ice Monitor можно будет адаптировать к более реалистичной среде, не меняя "
            "основной концепции. Иначе говоря, текущая версия задаёт каркас, который можно "
            "масштабировать по мере роста требований и доступных ресурсов."
        ),
        build_paragraph(
            "С промышленной точки зрения система уже сейчас демонстрирует несколько важных "
            "качеств: модульность, воспроизводимость, прозрачность данных и связность "
            "аналитических слоёв. Эти качества не всегда видны в коротком демо, но именно "
            "они определяют пригодность архитектуры к дальнейшему развитию. Для учебного "
            "проекта это означает, что создан не одноразовый макет, а задел для "
            "последующих исследований и практических доработок."
        ),
        build_paragraph(
            "В итоге можно утверждать, что Ice Monitor удовлетворяет как требованиям "
            "предметной области, так и требованиям академической постановки задачи. Он "
            "показывает, как глубокое обучение, большие данные и инженерная дисциплина "
            "могут быть объединены в одной системе, и при этом остаётся достаточно "
            "компактным, чтобы его можно было осмыслить в рамках курсовой работы."
        ),
        build_paragraph(
            "Именно такая завершённость делает проект удобным объектом для защиты: в нём "
            "есть и понятный результат, и ясная методология, и перспективы дальнейшего "
            "развития. Для курсовой работы это означает достижение основной цели не только "
            "на уровне алгоритмов, но и на уровне системного мышления."
        ),
    ]

    insert_before(body, "ГЛАВА 3. АРХИТЕКТУРА СИСТЕМЫ", chapter_2_final)
    insert_before(body, "ЗАКЛЮЧЕНИЕ", chapter_5_final)

    write_docx(docx_path, entries, root, root_open_tag)
    print(f"Updated: {docx_path}")


if __name__ == "__main__":
    main()
