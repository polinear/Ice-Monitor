from __future__ import annotations

from pathlib import Path

from expand_kursovaya_docx import (
    build_paragraph,
    insert_before,
    load_document_xml,
    write_docx,
)


def main() -> None:
    repo_root = Path(__file__).resolve().parents[1]
    docx_path = repo_root / "kursovaya" / "Курсовая ГО.docx"
    if not docx_path.exists():
        raise FileNotFoundError(docx_path)

    root, entries, root_open_tag = load_document_xml(docx_path)
    body = root.find("{http://schemas.openxmlformats.org/wordprocessingml/2006/main}body")
    if body is None:
        raise RuntimeError("word/document.xml has no body")

    extra = [
        build_paragraph("5.13. Методическая ценность проекта для учебной подготовки", "Heading2"),
        build_paragraph(
            "Методическая ценность Ice Monitor состоит в том, что он позволяет изучать "
            "несколько классов технологий в рамках единого и осмысленного сценария. "
            "Студент или преподаватель видит не абстрактные сервисы, а систему, где "
            "каждый компонент имеет понятную функцию: камера поставляет кадры, нейросеть "
            "их интерпретирует, потоковые инструменты передают результаты, а аналитический "
            "слой превращает их в отчётные формы. Такая прозрачность особенно полезна в "
            "учебной среде, потому что облегчает объяснение сложных связей между модулями."
        ),
        build_paragraph(
            "Проект удобен и как основа для повторного использования в последующих "
            "работах. Его можно развивать в сторону более сложной модели глубокого "
            "обучения, расширять набор классов, добавлять временной анализ или переносить "
            "на другие предметные области, где требуется объединение компьютерного зрения "
            "и больших данных. Тем самым Ice Monitor не ограничивается одной темой, а "
            "становится универсальным учебным кейсом, на котором можно проверять новые "
            "технологии и подходы без необходимости строить инфраструктуру заново."
        ),
        build_paragraph(
            "Ещё одно достоинство состоит в том, что архитектура формирует правильное "
            "представление о жизненном цикле данных. В отличие от упрощённых учебных "
            "примеров, где модель обучается отдельно от хранилища и интерфейса, здесь "
            "видно, как результат вычисления сразу становится частью более крупного "
            "аналитического процесса. Такой взгляд важен для современного инженера по "
            "данным, поскольку реальные системы почти всегда строятся именно как цепочка "
            "преобразований, а не как изолированные алгоритмы."
        ),
        build_paragraph(
            "Поэтому Ice Monitor можно рассматривать как удачную демонстрацию "
            "междисциплинарного подхода. Работа объединяет теорию глубокого обучения, "
            "архитектуру распределённых систем, проектирование ETL-процессов, принципы "
            "наблюдаемости и основы визуальной аналитики. Такая комбинация особенно хорошо "
            "подходит для итоговой аттестации, поскольку показывает, что автор умеет "
            "мыслить не только на уровне кода, но и на уровне целостной системы."
        ),
    ]

    insert_before(body, "ЗАКЛЮЧЕНИЕ", extra)

    write_docx(docx_path, entries, root, root_open_tag)
    print(f"Updated: {docx_path}")


if __name__ == "__main__":
    main()
