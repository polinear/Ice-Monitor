from __future__ import annotations

from pathlib import Path

from expand_kursovaya_docx import (
    build_paragraph,
    insert_before,
    load_document_xml,
    write_docx,
)


def main() -> None:
    repo_root = Path(__file__).resolve().parents[1]
    docx_path = repo_root / "kursovaya" / "Курсовая ГО.docx"
    if not docx_path.exists():
        raise FileNotFoundError(docx_path)

    root, entries, root_open_tag = load_document_xml(docx_path)
    body = root.find("{http://schemas.openxmlformats.org/wordprocessingml/2006/main}body")
    if body is None:
        raise RuntimeError("word/document.xml has no body")

    extra = [
        build_paragraph("5.10. Сценарий защиты и практическая демонстрация системы", "Heading2"),
        build_paragraph(
            "Для защиты курсовой работы особенно важна последовательность демонстрации. "
            "Система Ice Monitor устроена так, что её можно показывать по нарастающей: "
            "сначала объяснить предметную область и показать, какие задачи решает "
            "сегментация ледовой обстановки, затем запустить горячий путь и продемонстрировать "
            "живую маску на видеопотоке, после чего перейти к историческим метрикам, Hive "
            "и BI-дашбордам. Такая последовательность помогает не терять внимание аудитории "
            "и одновременно показывает, что все части проекта связаны между собой."
        ),
        build_paragraph(
            "На этапе демонстрации полезно отдельно подчеркнуть, что система работает не "
            "только как визуальный интерфейс, но и как полноценный конвейер данных. "
            "Зритель видит, что кадр не просто отображается на экране, а проходит через "
            "захват, сериализацию, нейросетевую обработку, сохранение метрик и последующую "
            "аналитику. Это особенно важно для дисциплины по большим данным, потому что "
            "позволяет связать абстрактные теоретические понятия с конкретной рабочей "
            "реализацией. В итоге защита становится не только рассказом о программном "
            "коде, но и демонстрацией целостной архитектурной логики."
        ),
        build_paragraph(
            "Следующий сильный акцент касается глубокого обучения. На защите уместно "
            "показать, что модель не является автономным экспериментом ради самой модели, "
            "а решает конкретную прикладную задачу в условиях ограниченных ресурсов. "
            "Использование YOLOv11s-seg, двух специализированных весов и fallback-логики "
            "позволяет объяснить, как в проекте достигается баланс между точностью, "
            "скоростью и надёжностью. Такой баланс — один из ключевых вопросов "
            "практического deep learning, и его наличие делает работу содержательной в "
            "академическом смысле."
        ),
        build_paragraph(
            "Ещё один важный момент защиты связан с устойчивостью системы к неполадкам. "
            "Можно отдельно продемонстрировать, что при отсутствии одного из сервисов "
            "архитектура не распадается полностью: горячий путь сохраняет работоспособность "
            "на Redis, а диагностические сообщения помогают быстро понять источник проблемы. "
            "Для преподавателя это особенно убедительно, потому что показывает зрелость "
            "инженерного мышления: автор проекта учитывает не только нормальный режим "
            "работы, но и возможные сбои."
        ),
        build_paragraph(
            "Если рассматривать проект как задел на дальнейшее развитие, то его легко "
            "представить в более крупной инфраструктуре. К существующему контуру можно "
            "добавить реальный RTSP-источник, вынести хранение данных в кластер, обновить "
            "модель на более мощную архитектуру или ввести временной анализ кадров. "
            "Благодаря модульной структуре такие изменения не потребуют полной "
            "перепроектировки. Поэтому на защите можно честно сказать, что представлена не "
            "застывшая схема, а развиваемая платформа, которая уже сейчас выполняет свою "
            "практическую функцию."
        ),
        build_paragraph(
            "В целом сценарий защиты сводится к демонстрации трёх уровней ценности: "
            "алгоритмической, системной и прикладной. Алгоритмическая ценность состоит в "
            "нейросетевой сегментации. Системная — в организации горячего и холодного "
            "контуров. Прикладная — в том, что результат действительно можно использовать "
            "для наблюдения за ледовой обстановкой и поддержки принятия решений. Именно "
            "сочетание этих трёх уровней делает проект убедительным и завершённым."
        ),
    ]

    insert_before(body, "ЗАКЛЮЧЕНИЕ", extra)

    write_docx(docx_path, entries, root, root_open_tag)
    print(f"Updated: {docx_path}")


if __name__ == "__main__":
    main()
