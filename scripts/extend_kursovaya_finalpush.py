from __future__ import annotations

from pathlib import Path

from expand_kursovaya_docx import (
    build_paragraph,
    insert_before,
    load_document_xml,
    write_docx,
)


def main() -> None:
    repo_root = Path(__file__).resolve().parents[1]
    docx_path = repo_root / "kursovaya" / "Курсовая ГО.docx"
    if not docx_path.exists():
        raise FileNotFoundError(docx_path)

    root, entries, root_open_tag = load_document_xml(docx_path)
    body = root.find("{http://schemas.openxmlformats.org/wordprocessingml/2006/main}body")
    if body is None:
        raise RuntimeError("word/document.xml has no body")

    extra = [
        build_paragraph("5.12. Итоговая формула практической ценности проекта", "Heading2"),
        build_paragraph(
            "Практическая ценность Ice Monitor заключается в том, что в нём соединены "
            "сразу несколько уровней обработки информации: нейросетевой, потоковый, "
            "хранилищный и аналитический. Каждый из этих уровней сам по себе представляет "
            "интерес, но именно их совместная работа делает систему целостной. Такой "
            "подход особенно хорошо отражает современную тенденцию к построению "
            "интеллектуальных платформ, в которых данные непрерывно перемещаются между "
            "контуром захвата, контуром интерпретации и контуром принятия решения."
        ),
        build_paragraph(
            "С учебной точки зрения проект ценен ещё и тем, что его можно использовать как "
            "наглядный пример архитектуры для нескольких дисциплин одновременно. Здесь "
            "есть и глубокое обучение, и распределённые системы, и контейнеризация, и "
            "SQL-аналитика, и визуализация. Благодаря этому курсовая работа не сводится к "
            "одной узкой теме, а демонстрирует междисциплинарный характер современных "
            "информационных решений. Именно такая связность обычно и требуется от "
            "качественной академической разработки."
        ),
        build_paragraph(
            "Если смотреть на проект как на основу для будущих исследований, то наиболее "
            "перспективными выглядят три направления: переход к более точной модели "
            "сегментации, ввод временной логики в анализ кадров и усиление распределённой "
            "инфраструктуры. Эти шаги позволят не только повысить прикладную готовность "
            "системы, но и углубить исследовательскую часть, связанную с обработкой "
            "мультимодальных данных и анализом динамических сцен."
        ),
        build_paragraph(
            "Итоговая формула ценности проекта проста: Ice Monitor показывает, как "
            "теоретические методы глубокого обучения и технологии больших данных могут "
            "быть собраны в единую работающую систему, способную решать прикладную "
            "задачу, быть понятной при защите и оставаться открытой для дальнейшего "
            "развития. Для курсовой работы это означает выполнение не только формальных, "
            "но и содержательных целей."
        ),
    ]

    insert_before(body, "ЗАКЛЮЧЕНИЕ", extra)

    write_docx(docx_path, entries, root, root_open_tag)
    print(f"Updated: {docx_path}")


if __name__ == "__main__":
    main()
