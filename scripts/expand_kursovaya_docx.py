W_NS = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
XML_NS = "http://www.w3.org/XML/1998/namespace"
NS = {"w": W_NS}


def qn(tag: str) -> str:
    return f"{{{W_NS}}}{tag}"


def build_paragraph(text: str, style: str | None = None) -> ET.Element:
    paragraph = ET.Element(qn("p"))
    if style:
        p_pr = ET.SubElement(paragraph, qn("pPr"))
        p_style = ET.SubElement(p_pr, qn("pStyle"))
        p_style.set(qn("val"), style)

    run = ET.SubElement(paragraph, qn("r"))
    text_el = ET.SubElement(run, qn("t"))
    if text[:1].isspace() or text[-1:].isspace():
        text_el.set(f"{{{XML_NS}}}space", "preserve")
    text_el.text = text
    return paragraph


def paragraph_text(paragraph: ET.Element) -> str:
    return "".join(node.text or "" for node in paragraph.findall(".//w:t", NS)).strip()


def load_document_xml(docx_path: Path):
    with zipfile.ZipFile(docx_path, "r") as zf:
        entries = {info.filename: zf.read(info.filename) for info in zf.infolist()}
    xml_text = entries["word/document.xml"].decode("utf-8")
    root_open_tag_match = re.search(r"<w:document\b[^>]*>", xml_text)
    if root_open_tag_match is None:
        raise RuntimeError("Could not locate root document tag")
    root_open_tag = root_open_tag_match.group(0)

    # Preserve the original namespace prefixes where possible.
    for prefix, uri in set(re.findall(r'xmlns:([A-Za-z0-9_]+)="([^"]+)"', xml_text)):
        try:
            ET.register_namespace(prefix, uri)
        except ValueError:
            pass
    ET.register_namespace("w", W_NS)
    return ET.fromstring(xml_text), entries, root_open_tag


def insert_before(body: ET.Element, target_text: str, paragraphs: list[ET.Element]) -> None:
    target = None
    for child in body:
        if child.tag == qn("p") and paragraph_text(child) == target_text:
            target = child
            break
    if target is None:
        raise ValueError(f"Paragraph not found: {target_text}")

    idx = list(body).index(target)
    for paragraph in paragraphs:
        body.insert(idx, paragraph)
        idx += 1


def write_docx(
    docx_path: Path,
    entries: dict[str, bytes],
    document_root: ET.Element,
    root_open_tag: str,
) -> None:
    required_namespaces = {
        "xmlns:w14": "http://schemas.microsoft.com/office/word/2010/wordml",
        "xmlns:w15": "http://schemas.microsoft.com/office/word/2012/wordml",
        "xmlns:wp14": "http://schemas.microsoft.com/office/word/2010/wordprocessingDrawing",
    }
    for attr, uri in required_namespaces.items():
        if attr not in root_open_tag:
            root_open_tag = root_open_tag[:-1] + f' {attr}="{uri}">'

    xml_text = ET.tostring(document_root, encoding="utf-8", xml_declaration=True).decode("utf-8")
    generated_open_tag_match = re.search(r"<w:document\b[^>]*>", xml_text)
    if generated_open_tag_match is None:
        raise RuntimeError("Could not locate generated root document tag")
    xml_text = xml_text.replace(generated_open_tag_match.group(0), root_open_tag, 1)
    xml_bytes = xml_text.encode("utf-8")

    fd, tmp_name = tempfile.mkstemp(suffix=".docx", prefix=docx_path.stem + "_", dir=str(docx_path.parent))
    os.close(fd)
    tmp_path = Path(tmp_name)

    try:
        with zipfile.ZipFile(tmp_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
            for filename, data in entries.items():
                if filename == "word/document.xml":
                    zf.writestr(filename, xml_bytes)
                else:
                    zf.writestr(filename, data)
        tmp_path.replace(docx_path)
    finally:
        if tmp_path.exists():
            try:
                tmp_path.unlink()
            except OSError:
                pass


